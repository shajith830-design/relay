ALTER TABLE product_implementations
  ADD COLUMN IF NOT EXISTS success_criteria TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS acceptance_status TEXT NOT NULL DEFAULT 'not_started'
    CHECK (acceptance_status IN ('not_started', 'in_progress', 'accepted', 'not_accepted')),
  ADD COLUMN IF NOT EXISTS test_plan TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS training_status TEXT NOT NULL DEFAULT 'not_started'
    CHECK (training_status IN ('not_started', 'scheduled', 'in_progress', 'complete')),
  ADD COLUMN IF NOT EXISTS support_owner_name TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS support_owner_email TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS rollback_plan TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS go_live_status TEXT NOT NULL DEFAULT 'not_ready'
    CHECK (go_live_status IN ('not_ready', 'at_risk', 'ready', 'launched'));

CREATE TABLE IF NOT EXISTS product_launch_stakeholders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  display_name TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT '',
  approval_status TEXT NOT NULL DEFAULT 'pending'
    CHECK (approval_status IN ('pending', 'approved', 'blocked')),
  next_action TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (implementation_id, email)
);

CREATE TABLE IF NOT EXISTS product_launch_risks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  category TEXT NOT NULL DEFAULT 'Other',
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 240),
  owner_name TEXT NOT NULL DEFAULT '',
  owner_email TEXT NOT NULL DEFAULT '',
  severity TEXT NOT NULL DEFAULT 'medium'
    CHECK (severity IN ('low', 'medium', 'high', 'critical')),
  status TEXT NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'mitigating', 'resolved')),
  next_action TEXT NOT NULL DEFAULT '',
  due_at TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
