CREATE TABLE IF NOT EXISTS product_capacity_plans (
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES product_users(id) ON DELETE CASCADE,
  week_start TEXT NOT NULL,
  available_minutes INTEGER NOT NULL DEFAULT 2400 CHECK (available_minutes BETWEEN 0 AND 10080),
  capacity_note TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (workspace_id, user_id, week_start)
);

CREATE TABLE IF NOT EXISTS product_time_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES product_users(id) ON DELETE SET NULL,
  work_date TEXT NOT NULL,
  minutes INTEGER NOT NULL CHECK (minutes BETWEEN 1 AND 1440),
  billable BOOLEAN NOT NULL DEFAULT TRUE,
  note TEXT NOT NULL DEFAULT '',
  hourly_rate NUMERIC(12,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS product_time_entries_implementation_idx
  ON product_time_entries(implementation_id, work_date);

CREATE TABLE IF NOT EXISTS product_financial_plans (
  implementation_id INTEGER PRIMARY KEY REFERENCES product_implementations(id) ON DELETE CASCADE,
  budget_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  forecast_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  actual_cost NUMERIC(12,2) NOT NULL DEFAULT 0,
  invoice_status TEXT NOT NULL DEFAULT 'not_started'
    CHECK (invoice_status IN ('not_started', 'draft', 'sent', 'paid', 'overdue')),
  invoice_reference TEXT NOT NULL DEFAULT '',
  margin_note TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product_approval_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  approval_type TEXT NOT NULL DEFAULT 'other',
  approver_name TEXT NOT NULL DEFAULT '',
  approver_email TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  due_at TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE product_implementations
  ADD COLUMN IF NOT EXISTS sow_scope TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS sow_milestones TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS sow_exclusions TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS stage_gate_status TEXT NOT NULL DEFAULT 'kickoff'
    CHECK (stage_gate_status IN ('kickoff', 'configuration', 'testing', 'launch', 'hypercare', 'complete'));

CREATE TABLE IF NOT EXISTS product_calendar_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  start_at TEXT NOT NULL,
  end_at TEXT NOT NULL DEFAULT '',
  event_type TEXT NOT NULL DEFAULT 'meeting',
  external_url TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
