ALTER TABLE product_process_steps
  ADD COLUMN IF NOT EXISTS customer_visible BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE product_implementation_steps
  ADD COLUMN IF NOT EXISTS customer_visible BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS product_workspace_notification_settings (
  workspace_id INTEGER PRIMARY KEY REFERENCES product_workspaces(id) ON DELETE CASCADE,
  email_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  reminder_days_before INTEGER NOT NULL DEFAULT 2 CHECK (reminder_days_before BETWEEN 0 AND 30),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product_workspace_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key TEXT NOT NULL UNIQUE,
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  implementation_id INTEGER REFERENCES product_implementations(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'sent', 'failed')),
  attempts INTEGER NOT NULL DEFAULT 0,
  email_sent_at TIMESTAMPTZ,
  slack_sent_at TIMESTAMPTZ,
  hubspot_synced_at TIMESTAMPTZ,
  available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS product_workspace_events_pending_idx
  ON product_workspace_events(status, available_at, id);

CREATE TABLE IF NOT EXISTS product_workspace_integrations (
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  provider TEXT NOT NULL CHECK (provider IN ('hubspot', 'slack')),
  access_token_cipher TEXT NOT NULL,
  refresh_token_cipher TEXT NOT NULL DEFAULT '',
  webhook_url_cipher TEXT NOT NULL DEFAULT '',
  token_expires_at TIMESTAMPTZ,
  external_account_id TEXT NOT NULL DEFAULT '',
  connected_by INTEGER REFERENCES product_users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (workspace_id, provider)
);

CREATE TABLE IF NOT EXISTS product_integration_states (
  state_hash TEXT PRIMARY KEY,
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  provider TEXT NOT NULL CHECK (provider IN ('hubspot', 'slack')),
  created_by INTEGER NOT NULL REFERENCES product_users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS product_integration_states_expiry_idx
  ON product_integration_states(expires_at);

CREATE TABLE IF NOT EXISTS product_hubspot_implementation_links (
  implementation_id INTEGER PRIMARY KEY REFERENCES product_implementations(id) ON DELETE CASCADE,
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  deal_id TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
