  ON audit_logs(actor_id, "timestamp" DESC);

CREATE OR REPLACE FUNCTION prevent_audit_log_mutation() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE'
    AND current_setting('relay.audit_privacy_scrub', TRUE) = 'on'
    AND NEW.actor_email = ''
    AND NEW.ip_address = ''
    AND (to_jsonb(NEW) - 'actor_email' - 'ip_address')
      = (to_jsonb(OLD) - 'actor_email' - 'ip_address') THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'Audit log records are immutable.';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS audit_logs_immutable ON audit_logs;
CREATE TRIGGER audit_logs_immutable
  BEFORE UPDATE OR DELETE ON audit_logs
  FOR EACH ROW EXECUTE FUNCTION prevent_audit_log_mutation();
