CREATE TABLE IF NOT EXISTS product_change_orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 160),
  scope_description TEXT NOT NULL CHECK (char_length(scope_description) BETWEEN 1 AND 4000),
  additional_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (additional_fee >= 0),
  timeline_extension_days INTEGER NOT NULL DEFAULT 0 CHECK (timeline_extension_days BETWEEN 0 AND 3650),
  status TEXT NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'pending_client', 'approved', 'rejected')),
  signed_by_email TEXT NOT NULL DEFAULT '',
  signed_ip TEXT NOT NULL DEFAULT '',
  signed_at TIMESTAMPTZ,
  created_by INTEGER REFERENCES product_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id, implementation_id)
);
