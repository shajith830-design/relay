CREATE UNIQUE INDEX IF NOT EXISTS product_implementations_hubspot_source_idx
  ON product_implementations(workspace_id, hubspot_source_deal_id)
  WHERE hubspot_source_deal_id != '';

ALTER TABLE product_workspace_integrations
  ADD COLUMN IF NOT EXISTS hubspot_onboarding_pipeline_id TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS hubspot_onboarding_stage_id TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS hubspot_onboarding_template_id INTEGER
    REFERENCES product_templates(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS hubspot_onboarding_last_synced_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS hubspot_onboarding_last_error TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS hubspot_onboarding_last_error_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS product_customer_contacts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  display_name TEXT NOT NULL DEFAULT '',
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  invitation_sent_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  last_activity_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (implementation_id, email)
);
CREATE INDEX IF NOT EXISTS product_customer_contacts_active_idx
  ON product_customer_contacts(implementation_id, expires_at)
  WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS product_customer_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  contact_id INTEGER REFERENCES product_customer_contacts(id) ON DELETE SET NULL,
  sender_role TEXT NOT NULL CHECK (sender_role IN ('customer', 'team')),
  sender_name TEXT NOT NULL DEFAULT '',
  sender_email TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS product_customer_messages_thread_idx
  ON product_customer_messages(implementation_id, created_at, id);

CREATE TABLE IF NOT EXISTS product_customer_files (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  contact_id INTEGER REFERENCES product_customer_contacts(id) ON DELETE SET NULL,
  uploaded_by_role TEXT NOT NULL CHECK (uploaded_by_role IN ('customer', 'team')),
  uploaded_by_name TEXT NOT NULL DEFAULT '',
  filename TEXT NOT NULL,
  content_type TEXT NOT NULL CHECK (content_type IN ('application/pdf', 'image/png', 'image/jpeg')),
  size_bytes INTEGER NOT NULL CHECK (size_bytes BETWEEN 1 AND 5242880),
  content BYTEA NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS product_customer_files_implementation_idx
  ON product_customer_files(implementation_id, created_at, id);

CREATE TABLE IF NOT EXISTS product_hubspot_imports (
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  deal_id TEXT NOT NULL,
  pipeline_id TEXT NOT NULL,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  invitation_sent_at TIMESTAMPTZ,
  PRIMARY KEY (workspace_id, deal_id),
  UNIQUE (implementation_id)
);
