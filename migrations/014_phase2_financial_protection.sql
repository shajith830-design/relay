ALTER TABLE product_memberships
  ADD COLUMN IF NOT EXISTS default_internal_cost_rate NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (default_internal_cost_rate >= 0),
  ADD COLUMN IF NOT EXISTS default_billable_rate NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (default_billable_rate >= 0);

ALTER TABLE product_implementations
  ADD COLUMN IF NOT EXISTS base_onboarding_fee NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (base_onboarding_fee >= 0),
  ADD COLUMN IF NOT EXISTS budget_type TEXT NOT NULL DEFAULT 'fixed_hours'
    CHECK (budget_type IN ('fixed_hours', 'fixed_fee', 'time_and_materials')),
  ADD COLUMN IF NOT EXISTS budget_limit NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (budget_limit >= 0),
  ADD COLUMN IF NOT EXISTS hard_lock_on_exceed BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS last_alert_threshold_sent INTEGER NOT NULL DEFAULT 0
    CHECK (last_alert_threshold_sent IN (0, 75, 90, 100));

ALTER TABLE product_time_entries
  ADD COLUMN IF NOT EXISTS task_id INTEGER REFERENCES product_implementation_steps(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS internal_cost_rate_snapshot NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (internal_cost_rate_snapshot >= 0),
  ADD COLUMN IF NOT EXISTS client_bill_rate_snapshot NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (client_bill_rate_snapshot >= 0),
  ADD COLUMN IF NOT EXISTS rate_snapshot_present BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS logged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

UPDATE product_time_entries SET logged_at = created_at;

UPDATE product_time_entries
SET client_bill_rate_snapshot = hourly_rate
WHERE client_bill_rate_snapshot = 0 AND hourly_rate > 0;

CREATE INDEX IF NOT EXISTS product_time_entries_task_idx
  ON product_time_entries(task_id, logged_at DESC);
CREATE INDEX IF NOT EXISTS product_time_entries_logged_at_idx
  ON product_time_entries(implementation_id, logged_at, id);

CREATE TABLE IF NOT EXISTS product_budget_overrides (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  implementation_id INTEGER NOT NULL REFERENCES product_implementations(id) ON DELETE CASCADE,
  granted_by INTEGER REFERENCES product_users(id) ON DELETE SET NULL,
  reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 1000),
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS product_budget_overrides_active_idx
  ON product_budget_overrides(implementation_id, expires_at)
  WHERE revoked_at IS NULL;
