CREATE TABLE IF NOT EXISTS product_salesforce_sku_template_mappings (
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  sku TEXT NOT NULL CHECK (BTRIM(sku) != '' AND LENGTH(sku) <= 120),
  template_id INTEGER NOT NULL REFERENCES product_templates(id) ON DELETE RESTRICT,
  updated_by INTEGER REFERENCES product_users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (workspace_id, sku)
);

CREATE INDEX IF NOT EXISTS product_salesforce_sku_template_mappings_template_idx
  ON product_salesforce_sku_template_mappings(workspace_id, template_id);

CREATE TABLE IF NOT EXISTS product_salesforce_imports (
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  opportunity_id TEXT NOT NULL,
  opportunity_name TEXT NOT NULL DEFAULT '',
  implementation_id INTEGER REFERENCES product_implementations(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'failed' CHECK (status IN ('failed', 'imported')),
  last_error TEXT NOT NULL DEFAULT '',
  imported_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (workspace_id, opportunity_id),
  CHECK (BTRIM(opportunity_id) != '' AND LENGTH(opportunity_id) <= 30)
);

CREATE INDEX IF NOT EXISTS product_salesforce_imports_pending_idx
  ON product_salesforce_imports(workspace_id, updated_at)
  WHERE status = 'failed';

CREATE TABLE IF NOT EXISTS product_external_issue_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id INTEGER NOT NULL REFERENCES product_workspaces(id) ON DELETE CASCADE,
  task_id INTEGER NOT NULL REFERENCES product_implementation_steps(id) ON DELETE CASCADE,
  provider TEXT NOT NULL CHECK (provider IN ('jira', 'linear')),
  external_issue_id TEXT NOT NULL,
  external_key TEXT NOT NULL,
  external_url TEXT NOT NULL,
  last_status TEXT NOT NULL DEFAULT 'open',
  last_error TEXT NOT NULL DEFAULT '',
  last_synced_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  created_by INTEGER REFERENCES product_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (task_id, provider),
  UNIQUE (workspace_id, provider, external_issue_id)
);

CREATE INDEX IF NOT EXISTS product_external_issue_links_poll_idx
  ON product_external_issue_links(provider, last_synced_at, id);
